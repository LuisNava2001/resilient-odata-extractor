"""Runs every failure scenario against a real local mock server and records the traces for the static demo.

Waits (Retry-After and backoff) go through a virtual clock: they are computed and recorded exactly as in a real
run, but not slept, so the demo finishes in seconds. Network timeouts are real (short) timeouts. Volatile values
(ports, byte counts, elapsed time) are left out so the output is identical on every run.
"""

from __future__ import annotations

import json
import random
from typing import Any

from .client import ClientConfig, ODataClient, RetryPolicy
from .faults import DEMO_ORDER, SCENARIOS
from .mock_server import MockServer
from .pipeline import run as run_pipeline
from .transport import VirtualClock

DEMO_TIMEOUT = 0.4
DEMO_SEED = 7


def run_scenario(name: str) -> dict[str, Any]:
    scenario = SCENARIOS[name]
    with MockServer(name) as server:
        config = ClientConfig(service_root=server.url, timeout=DEMO_TIMEOUT, page_size=50,
                              retry=RetryPolicy(max_attempts=4, base_delay=0.5, max_delay=8.0))
        client = ODataClient(config, clock=VirtualClock(), rng=random.Random(DEMO_SEED))
        outcome = run_pipeline(config, scenario.entity, client=client)
    run, integrity = outcome.run, outcome.integrity
    metrics = run.metrics.to_dict()
    phases = metrics["requests_by_phase"]
    timeline = [e for e in run.timeline if e["phase"] == "extract"]
    recon_events = [e for e in run.timeline if e["phase"] == "reconcile"]
    if recon_events:
        recon = run.reconciliation
        detail = (f"key reconciliation: {phases.get('reconcile', 0)} request(s), {len(recon.ids)} IDs"
                  if recon and recon.available else f"key reconciliation unavailable: {recon.reason if recon else ''}")
        timeline.append({"seq": len(timeline) + 1, "phase": "reconcile", "kind": "summary", "detail": detail})
    return {
        "name": name, "title": scenario.title, "description": scenario.description, "conformant": scenario.conformant,
        "expected_status": scenario.expected_status, "status": integrity.status,
        "as_expected": integrity.status == scenario.expected_status,
        "metrics": {"requests_total": metrics["requests_total"], "requests_extract": phases.get("extract", 0),
                    "requests_reconcile": phases.get("reconcile", 0),
                    "pages": integrity.counts.get("pages", len(run.pages)),
                    "records_received": integrity.counts.get("records_received", 0),
                    "unique_records": integrity.counts.get("unique_records", 0), "retries": metrics["retries"],
                    "retries_by_reason": metrics["retries_by_reason"], "wait_seconds": metrics["wait_seconds"],
                    "http_statuses": metrics["http_statuses"],
                    "problems": len(integrity.reasons) + len(integrity.warnings)},
        "counts": integrity.counts, "reasons": integrity.reasons, "warnings": integrity.warnings, "basis": integrity.basis,
        "timeline": timeline,
    }


def run_all(only: str | None = None) -> list[dict[str, Any]]:
    return [run_scenario(name) for name in DEMO_ORDER if only in (None, name)]


def render(traces: list[dict[str, Any]]) -> str:
    payload = {"generated_by": "odata-extractor demo", "dataset": "synthetic (Halcyon Equipment Services, fictional)",
               "entity": "WorkOrders", "virtual_clock": True, "scenarios": traces}
    return ("// Generated by `python -m odata_extractor demo --out demo/data.js` from real runs against the local mock server.\n"
            "// Deterministic: fixed seed, virtual clock for waits, no ports or timings. Do not edit by hand.\n"
            "window.EXTRACTOR_DEMO = " + json.dumps(payload, indent=1, ensure_ascii=True) + ";\n")
